-- ============================================================
-- V2 用户账号唯一约束
--
-- 目的：账号唯一性由数据库保证，而不是依赖应用层的"先查后插"或单机 synchronized。
--       原实现的 `synchronized (userAccount.intern())` 只在单实例内有效，
--       多实例并发注册同一账号会各插一条。
--
-- 前置条件：`user` 表中不能有重复 userAccount。
--           执行前先运行 checks/duplicate_accounts_report.sql 确认
--           duplicate_account_count = 0。
--           若存在重复，本语句会以 MySQL 1062 失败——这是**期望的安全失败**，
--           不会留下半成品状态（ALTER 失败即整体回滚），也不会自动删改任何账号。
--
-- 关于软删除：唯一约束覆盖全部记录，**包含 isDelete=1 的软删除账号**。
--           即账号在软删除后仍然占用，不能被重新注册（避免隐式账号重用、
--           以及旧提交记录与新账号归属混淆）。这是本项目的既定规则。
--           因此应用层的唯一性预检查必须同样不区分 isDelete。
--
-- 关于大小写与空格：比较沿用列自身的排序规则 utf8mb4_unicode_ci，
--           大小写不敏感且忽略尾部空格（实测：'Alice'='alice'，'abc'='abc '）。
--           这与应用层现有查询行为一致，不改变既有语义。
-- ============================================================

ALTER TABLE `user`
    ADD UNIQUE KEY uk_user_userAccount (userAccount);
